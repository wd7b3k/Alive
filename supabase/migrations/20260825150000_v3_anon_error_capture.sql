-- Ошибки до входа.
--
-- С 22 августа продукт открывается без аккаунта: человек читает «Факты», смотрит
-- Связки и только потом решает, входить ли. Значит, часть поломок случается до входа —
-- и это самые дорогие поломки, потому что человек уходит, не начав, и об этом никто не
-- узнаёт.
--
-- Право писать в system_errors выдано только `authenticated` (20260817170000), поэтому
-- сейчас такие ошибки не доходят до базы вообще. Здесь anon получает ровно одно право:
-- добавить строку без user_id.
--
-- Осознанный размен: анонимный endpoint, в который можно писать, — это endpoint,
-- который можно засорить. Персональных данных в таблице нет, стоимость мусора —
-- строки в журнале ошибок, и её видно тем же экраном здоровья продукта. Обратное —
-- слепота ровно в той части воронки, где человек ещё ничего не решил — обходится
-- дороже. Если мусор появится, ограничение ставится на шлюзе, а не отзывом этого
-- гранта.
grant insert on public.system_errors to anon;

drop policy if exists system_errors_insert_anon on public.system_errors;
create policy system_errors_insert_anon on public.system_errors
  for insert to anon
  -- Только безымянная запись. Анонимный клиент не может приписать ошибку человеку:
  -- ни своему аккаунту, которого нет, ни чужому.
  with check (user_id is null);
