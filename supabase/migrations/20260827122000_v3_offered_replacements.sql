-- Что человеку показали, а не только что он выбрал.
--
-- H-ALIVE-002 — главная гипотеза продукта: «персонализированный подбор ответов работает
-- лучше общего каталога». Проверить её по тому, что лежит в базе, было **невозможно**:
-- ранжирование целиком клиентское (`app/src/data.ts`), а в эпизоде оставался только
-- выбранный код. Ни показанный список, ни его порядок, ни факт персонализации никуда не
-- писались; `episode_actions.payload` уходил пустым объектом.
--
-- То есть пилот можно было провести целиком, собрать эпизоды и не суметь ответить на
-- вопрос, ради которого он затевался. Эти три колонки — минимум, которого не хватало.

alter table public.episodes
  add column if not exists offered_replacements text[] not null default '{}'::text[],
  add column if not exists offer_personalized boolean,
  add column if not exists offer_reason text;

comment on column public.episodes.offered_replacements is
  'Коды замен в том порядке, в каком они были показаны. Пустой массив — экран ответа не открывался.';
comment on column public.episodes.offer_personalized is
  'Подбор опирался на личную историю (true) или на общий каталог (false). Null — экран не открывался.';
comment on column public.episodes.offer_reason is
  'Короткий код правила подбора. Нужен, чтобы отличать «личная история» от «карта контекстов» при разборе результата.';

-- Индекс не нужен: колонки читаются только агрегатами витрины метрик, которые и так
-- проходят по всем эпизодам окна.

-- Порядок в массиве значим, и это не самоочевидно из типа. Проверка гарантирует, что в
-- него не попадут пустые коды: пустая строка среди кодов сломала бы сопоставление с
-- каталогом молча, показав «показали замену без названия».
alter table public.episodes
  drop constraint if exists episodes_offered_replacements_nonempty;
alter table public.episodes
  add constraint episodes_offered_replacements_nonempty check (
    not (offered_replacements && array['']::text[])
  );

-- Ссылочной целостности с каталогом здесь нет намеренно: код замены, удалённой из
-- каталога после эпизода, всё равно остаётся правдой о том, что человеку показали.
-- Внешний ключ на массив невозможен, а чистка задним числом переписала бы историю.
