-- Согласие участника.
--
-- Habitoff — исследование поведения, связанного с зависимостью, и до этой миграции в нём
-- не было ни одного места, где человек соглашается участвовать. `PRIVACY_AND_DATA.md` §9
-- обещает «понятный consent», §20 требует спросить заново при изменении статуса —
-- механизма не существовало ни в каком виде. Страница `/experiment` содержательна, но
-- её нельзя пропустить-и-подтвердить, и факт прочтения нигде не оставался.
--
-- Здесь появляется запись самого факта. Согласие даётся на экране входа галочкой рядом
-- с кнопками провайдеров: до входа профиля ещё нет, поэтому клиент проставляет отметку
-- первым же запросом после возврата от провайдера.
--
-- Версия хранится строкой, а не флагом, намеренно: когда формулировка изменится,
-- сравнение с текущей версией само покажет, у кого согласие устарело, и §20 выполняется
-- без отдельной таблицы. Значение задаёт клиент (`CONSENT_VERSION`), а не база: текст
-- живёт в интерфейсе, и расходиться им нельзя.

alter table public.profiles
  add column if not exists consent_version text,
  add column if not exists consent_accepted_at timestamptz;

-- Полу-состояние «версия есть, даты нет» означало бы согласие неизвестно когда, а
-- «дата есть, версии нет» — согласие неизвестно на что. Ни то ни другое не годится как
-- запись согласия, поэтому его нельзя записать.
alter table public.profiles
  drop constraint if exists profiles_consent_complete;
alter table public.profiles
  add constraint profiles_consent_complete check (
    (consent_version is null and consent_accepted_at is null)
    or (consent_version is not null and btrim(consent_version) <> '' and consent_accepted_at is not null)
  );

comment on column public.profiles.consent_version is
  'Версия текста согласия, на который человек согласился. Null — согласие не давалось.';
comment on column public.profiles.consent_accepted_at is
  'Когда участник подтвердил согласие. Пишется клиентом после первого входа.';

