-- myths_catalog.replacement_codes у мифа focus_better ссылается на код `water`,
-- которого в replacements_catalog нет — есть `water_pause` («Стакан воды»). Массив не
-- умеет иметь внешний ключ, поэтому ссылка молча висела и одна из трёх предложенных
-- замен просто не находилась. Ниже — точечная замена кода, без изменения смысла
-- карточки.
update public.myths_catalog
   set replacement_codes = array_replace(replacement_codes, 'water', 'water_pause')
 where 'water' = any(replacement_codes);

-- ---------------------------------------------------------------------------
-- Проверки
-- ---------------------------------------------------------------------------
do $$
declare
  missing text;
  latin text;
  dangling text;
  allowed text := '(ALIVE|CDC|JAMA|Freedom Fund|light|low-tar)';
begin
  -- 1. Третий слот заполнен у каждой карточки: без него форма
  --    «что известно → что это меняет для тебя» нигде не собирается.
  select string_agg(code, ', ') into missing from (
    select code from public.facts_catalog where changes_ru is null or btrim(changes_ru) = ''
    union all
    select code from public.myths_catalog where changes_ru is null or btrim(changes_ru) = ''
  ) x;
  if missing is not null then
    raise exception 'Карточки без «что это меняет для тебя»: %', missing;
  end if;

  -- 2. Латиница в тексте, который человек читает. Ровно та проблема, ради которой
  --    писалась миграция, поэтому она проверяется, а не остаётся на внимательность
  --    следующего редактора. Разрешены только имена: ALIVE, CDC, JAMA, Freedom Fund
  --    и слова light / low-tar, которые сами являются предметом карточки.
  select string_agg(code || ' [' || field || ']', ', ') into latin from (
    select code, 'short_text' field, short_text t from public.facts_catalog
    union all select code, 'full_text', full_text from public.facts_catalog
    union all select code, 'changes_ru', changes_ru from public.facts_catalog
    union all select code, 'short_reframe', short_reframe from public.myths_catalog
    union all select code, 'explanation', explanation from public.myths_catalog
    union all select code, 'changes_ru', changes_ru from public.myths_catalog
  ) x
  where regexp_replace(t, allowed, '', 'gi') ~ '[A-Za-z]';
  if latin is not null then
    raise exception 'В читаемом тексте осталась латиница: %', latin;
  end if;

  -- 3. Ни одна карточка не ссылается на несуществующую замену или триггер.
  select string_agg(what, '; ') into dangling from (
    select 'замена ' || rc as what from (select unnest(replacement_codes) rc from public.myths_catalog) a
     where not exists (select 1 from public.replacements_catalog r where r.code = a.rc)
    union all
    select 'триггер ' || tc from (select unnest(trigger_codes) tc from public.myths_catalog) b
     where not exists (select 1 from public.triggers_catalog t where t.code = b.tc)
  ) y;
  if dangling is not null then
    raise exception 'Карточка ссылается на несуществующий код: %', dangling;
  end if;
end $$;

alter table public.facts_catalog alter column changes_ru set not null;
alter table public.myths_catalog alter column changes_ru set not null;

commit;
