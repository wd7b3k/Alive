-- Редакторский проход по «Фактам» и «Мифам», которые уже лежат в проде.
--
-- Контент в facts_catalog и myths_catalog содержательный и с источниками, но написан
-- наполовину по-английски: «В EMA studies momentary craving связан с lapse»,
-- «behavioural target», «Study included 8 770 participants and defined heavy smoking
-- as at least 20 pack-years». Человеку, который открыл раздел в момент тяги, читать
-- это невозможно. Здесь весь текст переписан по-русски, без потери чисел, названий
-- исследований и оговорок.
--
-- Второе: владелец задал форму карточки «Миф → что известно → что это меняет для тебя».
-- Третьего слота в обеих таблицах нет — у фактов есть short_text и full_text, у мифов
-- short_reframe и explanation, и оба вторых поля заняты уточнением, а не выводом.
-- Поэтому добавляется одна колонка changes_ru: что из этого следует лично для читателя,
-- сегодня. Это добавление к прод-схеме, а не параллельная таблица.
--
-- Роли полей после этой миграции:
--   факт:  title        — утверждение
--          short_text   — что известно
--          full_text    — где данные заканчиваются (оговорка, границы)
--          changes_ru   — что это меняет для тебя
--   миф:   title          — само убеждение, как его произносит человек
--          short_reframe  — что известно
--          explanation    — механизм и детали
--          changes_ru     — что это меняет для тебя

