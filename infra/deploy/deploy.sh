#!/usr/bin/env bash
# Выкладка Habitoff. Канонический источник — этот файл; /srv/alive/deploy.sh является
# его копией и обновляется установкой из репозитория (infra/deploy/README.md).
#
# Почему он вообще оказался в репозитории. 30.08.2026 в 18:02 выкладка прошла наполовину:
# запущенная от root, она получила от каждой git-команды «detected dubious ownership in
# repository at /srv/alive/repo» — каталог принадлежит alive, а git отказывается работать
# в чужом репозитории. Скрипт при этом не остановился. Гейт грязного дерева выглядел так:
#
#     [[ -z "$(git status --porcelain)" ]] || { echo "ОТКАЗ: ..."; exit 1; }
#
# Упавший git пишет в stderr и не печатает ничего в stdout — значит подстановка пуста,
# значит условие истинно, значит гейт доволен. Проверка на «дерево чистое» пропускала
# ровно тот случай, ради которого она написана: когда о состоянии дерева ничего не
# известно. Сборка собралась из того, что лежало, `version.json` получил пустой `commit`,
# симлинк переключился, и прод сутки отдавал сборку без имени.
#
# Отсюда три правила этого файла:
#
# 1. Ни одна команда не проверяется по своему выводу. Проверяется код возврата.
# 2. От root не запускается вовсе. Дело не только в git: `npm ci` и сборка от root
#    оставляют в репозитории 9525 файлов чужого владельца, и следующая выкладка от alive
#    падает уже на них.
# 3. Симлинк переключается последним действием, после того как собранное проверено.
#    До этого момента любой отказ оставляет прод ровно таким, каким он был.

set -euo pipefail

REPO="${HABITOFF_REPO:-/srv/alive/repo}"
ROOT="${HABITOFF_ROOT:-/srv/alive}"
RELEASES="$ROOT/releases"
KEEP="${HABITOFF_KEEP_RELEASES:-5}"

die() { echo "ОТКАЗ: $*" >&2; exit 1; }

# --- 1. Кто запускает ------------------------------------------------------------
#
# Проверка стоит первой намеренно: она дешевле всех остальных и закрывает причину, а не
# следствие. `sudo deploy.sh` сохраняет SUDO_UID, и git по нему признаёт каталог своим —
# то есть беда наступает не от sudo как такового, а от запуска из-под root-сессии, где
# SUDO_UID нет. Разбирать эти случаи по отдельности незачем: выкладке права root не нужны
# ни для чего.
if [[ "$(id -u)" -eq 0 ]]; then
  owner="$(stat -c '%U' "$REPO" 2>/dev/null || echo '?')"
  die "выкладка запущена от root. Каталог $REPO принадлежит $owner; git от root в нём
  отказывается работать, а npm ci и сборка оставляют в нём файлы чужого владельца.
  Запускать так:  sudo -u $owner $0"
fi

owner="$(stat -c '%U' "$REPO")" || die "нет каталога $REPO"
if [[ "$owner" != "$(id -un)" ]]; then
  die "каталог $REPO принадлежит $owner, а выкладка идёт от $(id -un).
  Разный владелец — это git, который откажется читать репозиторий, и файлы сборки,
  которые следующая выкладка не сможет перезаписать. Запускать от $owner."
fi

cd "$REPO" || die "не смог перейти в $REPO"

# --- 1a. Скрипт обязан быть тем, что лежит в репозитории ----------------------------
#
# `/srv/alive/deploy.sh` — копия этого файла, и копия молча устаревает. 31.08.2026 так и
# вышло: в репозиторий добавился шаг выгрузки каталога для разметки, `main` уехал на
# прод, а выкладку по-прежнему делала копия без этого шага. Разметка `/knowledge`
# собралась без источников, и по логу выкладки это было никак не видно — шага там просто
# не было.
#
# Проверка стоит здесь, после `cd`, но до всего остального: она ничего не чинит сама,
# потому что чинить установкой от своего имени — значит переустанавливать себя на ходу.
repo_copy="$REPO/infra/deploy/deploy.sh"
self="$(readlink -f "$0")"
if [[ -f "$repo_copy" && "$self" != "$(readlink -f "$repo_copy")" ]] && ! cmp -s "$self" "$repo_copy"; then
  die "установленный $self отличается от $repo_copy.
  Копия устарела — обнови её и повтори:
    sudo install -m 755 -o $owner -g $owner $repo_copy $self"
fi

# --- 2. Git обязан отвечать -------------------------------------------------------
#
# Отдельная проверка до всех остальных: пока неизвестно, работает ли git, ни одному
# ответу про состояние дерева верить нельзя.
head_sha="$(git rev-parse HEAD)" || die "git в $REPO не отвечает — дальше идти нельзя"
[[ -n "$head_sha" ]] || die "git не вернул коммит"

branch="$(git rev-parse --abbrev-ref HEAD)" || die "git не вернул ветку"
[[ "$branch" == "main" ]] || die "прод собирается только с main, а здесь $branch"

# Код возврата, а не пустота вывода. Это и есть тот самый гейт, который 30.08 пропустил
# оборванную выкладку.
dirty="$(git status --porcelain)" || die "git status не выполнился"
if [[ -n "$dirty" ]]; then
  echo "$dirty" >&2
  die "рабочее дерево грязное — выложить то, чего нет в коммите, нельзя"
fi

# --- 2a. Собирается ли то, что лежит в origin --------------------------------------
#
# Гейты выше отвечают на вопрос «соответствует ли дерево своему коммиту». Ни один из них
# не отвечает на вопрос «тот ли это коммит»: дерево бывает идеально чистым, на ветке
# main — и при этом отставшим от origin/main на два десятка коммитов. 06.09.2026 так и
# вышло: выкладка собрала f76f8b7, когда в origin/main лежал d5aeed7, клон на сервере
# отставал на 22 коммита, скрипт напечатал «выложено», а прод не сдвинулся. Второй
# случай того же рода — упавший `git pull` в цепочке перед выкладкой: команда отказала,
# человек этого не заметил, deploy.sh пересобрал прежний коммит и снова отчитался
# успехом.
#
# Fetch делает сам скрипт. Ссылку обновляет ещё и мониторинг по своему расписанию
# (infra/monitoring/lib/fingerprint.sh), но выкладка не имеет права зависеть от того,
# успел ли пройти чужой таймер: сверка с протухшей ссылкой молча пропускает ровно тот
# случай, ради которого гейт написан. Fetch не трогает ни рабочее дерево, ни HEAD, ни
# current — он только делает ссылку правдивой.
#
# Отказ fetch — это отказ выкладки, а не «сверюсь с тем, что есть». Свежесть ссылки
# неизвестна, значит результат сверки ничего не значит.
#
# Чинить расхождение скрипт не будет. Рубеж, который сам чинит то, на что жалуется,
# перестаёт быть рубежом: выкладка тогда молча увозит на прод всё, что оказалось в
# origin/main, включая то, чего человек выкладывать не собирался. Отказ и готовая
# команда в тексте отказа — тот же приём, что в гейте копии скрипта выше.
fetch_timeout="${HABITOFF_FETCH_TIMEOUT:-60}"
fetch_rc=0
timeout "$fetch_timeout" git fetch --quiet origin main || fetch_rc=$?
if [[ "$fetch_rc" -ne 0 ]]; then
  if [[ "$fetch_rc" -eq 124 ]]; then
    why="fetch не уложился в $fetch_timeout с"
  else
    why="нет сети, недоступен GitHub, нет ключа или битая ссылка в .git"
  fi
  die "git fetch origin main не прошёл (код $fetch_rc: $why).
  Свежесть origin/main неизвестна, сверять $REPO не с чем — выкладка отменена,
  прод не тронут. Посмотреть, что именно сломалось:
    cd $REPO && git fetch origin main && git rev-parse HEAD FETCH_HEAD"
fi

# Сверяемся с FETCH_HEAD, а не с именем origin/main: FETCH_HEAD пишет этот самый fetch и
# всегда, а refs/remotes/origin/main обновляется попутно и зависит от refspec клона. Имя,
# свежесть которого зависит от настройки, даёт не ошибку, а тихое расхождение.
remote_sha="$(git rev-parse FETCH_HEAD)" || die "git rev-parse FETCH_HEAD не выполнился"
[[ -n "$remote_sha" ]] || die "git не вернул коммит origin/main"

if [[ "$head_sha" != "$remote_sha" ]]; then
  ahead='?'
  behind='?'
  if counts="$(git rev-list --left-right --count "$head_sha...$remote_sha")"; then
    read -r ahead behind <<<"$counts"
  fi
  if [[ "$ahead" == "0" ]]; then
    why="Клон отстал от origin/main на $behind коммит(ов). Подтянуть и повторить:
    cd $REPO && git pull --ff-only origin main"
  elif [[ "$ahead" == "?" ]]; then
    why="На сколько разошлись — сосчитать не удалось, разбирается человек. Если клон
  просто отстал, помогает:
    cd $REPO && git pull --ff-only origin main"
  else
    why="На сервере $ahead коммит(ов), которых нет в origin, и $behind в origin, которых
  нет здесь. Выкладка их не увезёт и не выбросит: разбирается человек — чья это работа и
  почему она живёт только на боевом клоне. git pull --ff-only тут не пройдёт и намеренно
  не предлагается."
  fi
  die "в $REPO лежит не тот коммит, что в origin/main.
  HEAD        $head_sha
  origin/main $remote_sha
  $why"
fi

echo "выкладываю $head_sha"

# --- 3. Миграции ------------------------------------------------------------------
files="$(ls supabase/migrations/*.sql | wc -l)" || die "не смог сосчитать файлы миграций"
# Пароль читается, но никуда не печатается и не уезжает: он нужен только psql.
PGPASSWORD="$(grep -m1 '^POSTGRES_PASSWORD=' /srv/supabase/.env | cut -d= -f2-)" \
  || die "не смог прочитать пароль Postgres"
export PGPASSWORD
rows="$(psql -h 127.0.0.1 -p 5432 -U postgres -d postgres -tAc \
  'select count(*) from supabase_migrations.schema_migrations')" \
  || die "база не ответила на запрос о миграциях"
unset PGPASSWORD
[[ "$files" == "$rows" ]] || die "миграций в репозитории $files, в базе $rows"

# --- 4. Сборка --------------------------------------------------------------------
#
# Выгрузки каталога здесь больше нет. До 05.09.2026 она делалась прямо на выкладке, и
# это было ошибкой того же рода, что и правка прода руками: сборка в CI и сборка на
# сервере давали разный результат, диффа контента никто не видел, а страницы, которые
# уедут в индекс, появлялись в обход ревью.
#
# С ADR-0017 каталог лежит выгрузкой в репозитории (`app/knowledge-catalog.json`), её
# снимает `scripts/dump-knowledge-catalog.mjs` и коммитит человек. Сборка падает сама,
# если выгрузка пуста, — отдельный гейт для этого не нужен.

( cd app && npm ci --silent && npm run build ) || die "сборка не прошла"

# --- 5. Собранное обязано быть подписано ------------------------------------------
#
# Ровно то, чего не хватило 30.08: сборка с пустым отпечатком доехала до прода и
# считалась исправной. Отпечаток ставит плагин habitoff-build-stamp в app/vite.config.ts
# из `git rev-parse HEAD`; пустая строка означает, что git при сборке молчал.
stamp="app/dist/version.json"
[[ -s "$stamp" ]] || die "сборка не оставила $stamp"
built_sha="$(sed -n 's/.*"commit"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$stamp")"
[[ -n "$built_sha" ]] || die "в $stamp пустой commit — сборка без отпечатка на прод не идёт"
[[ "$built_sha" == "$head_sha" ]] \
  || die "сборка подписана $built_sha, а дерево на $head_sha"
[[ -s app/dist/index.html ]] || die "в сборке нет index.html"

# Имя entry-чанка из index.html обязано существовать на диске: половина скопированной
# сборки выглядит как целая ровно до первого запроса.
chunk="$(sed -n 's|.*src="/assets/\(index-[A-Za-z0-9_-]*\.js\)".*|\1|p' app/dist/index.html | head -n 1)"
[[ -n "$chunk" ]] || die "в index.html нет ссылки на entry-чанк"
[[ -s "app/dist/assets/$chunk" ]] || die "index.html ссылается на $chunk, которого нет в сборке"

# --- 6. Публикация ----------------------------------------------------------------
#
# Каталог собирается целиком и только потом становится текущим. Незавершённая раскладка
# удаляется за собой: иначе через месяц в releases лежит десяток огрызков, неотличимых
# от настоящих релизов.
ts="$(date +%Y%m%d-%H%M%S)"
staged="$RELEASES/$ts"
published=0
# Ловушка на EXIT, а не на ERR: половина отказов здесь приходит через `|| die`, то есть
# через штатный exit, на который ERR не срабатывает. EXIT ловит все выходы разом.
cleanup_staged() {
  if [[ "$published" -eq 0 && -n "${staged:-}" && -d "$staged" ]]; then
    rm -rf "$staged"
    echo "незавершённая раскладка $staged убрана, current не тронут" >&2
  fi
  return 0
}
trap cleanup_staged EXIT

cp -r app/dist "$staged" || die "не смог разложить сборку в $staged"
rm -f "$staged"/assets/*.map
[[ -s "$staged/index.html" && -s "$staged/assets/$chunk" ]] \
  || die "разложенная сборка неполна"

# Что было опубликовано до этой выкладки — нужно, чтобы сообщить поисковику только об
# изменившихся адресах. Читается до переключения симлинка: после него `current` уже новый.
previous="$(readlink -f "$ROOT/current" 2>/dev/null || echo none)"
[[ -d "$previous" ]] || previous=none

ln -sfn "$staged" "$ROOT/current.new" || die "не смог создать временный симлинк"
mv -Tf "$ROOT/current.new" "$ROOT/current" || die "не смог переключить current"
published=1

# --- 7. Сообщить поисковикам ------------------------------------------------------
#
# IndexNow. Обход молодого домена идёт неделями, и раздел, выложенный и не замеченный
# месяц, для поиска не существует. Запрос делает сервер один раз, здесь; до браузера
# посетителя он не доходит, поэтому запрет внешних сервисов в рантайме не нарушен.
# Обоснование — docs/SEO_AND_ANALYTICS.md.
#
# Отправляются только изменившиеся адреса: слать все на каждой выкладке значит научить
# поисковик, что сигнал ничего не значит, — и в тот раз, когда изменение будет
# настоящим, его никто не прочитает.
#
# Отказ пинга выкладку не отменяет: симлинк уже переключён, сайт уже новый. Чужой
# сервер не имеет права объявить состоявшуюся выкладку неудачной.
node scripts/indexnow-ping.mjs --dist "$staged" --previous "$previous" || true

# --- 8. Уборка --------------------------------------------------------------------
ls -1dt "$RELEASES"/* | tail -n "+$((KEEP + 1))" | xargs -r rm -rf
echo "выложено $ts ($head_sha)"
