#!/usr/bin/env bash
# Следующий свободный номер постановки, разбора или записи сессии за сегодня.
#
# Зачем. Номер до сих пор брали глазами, и он разъезжался ровно так же, как разъезжались
# номера ADR до `next-adr.sh`. За 05.09.2026 в каталогах лежит пять коллизий сразу:
# `R-20260905-01` дважды, `T-20260905-11` дважды, `T-20260905-12` дважды, записи 004 и
# 005 за тот день — тоже дважды. Две сессии в один день считают «последний занятый» по
# своей копии каталога и приходят к одному числу.
#
# Каталог считает сам:
#
#   scripts/next-id.sh T          -> T-20260906-05
#   scripts/next-id.sh R          -> R-20260906-02
#   scripts/next-id.sh session    -> 004
#
# `R` и `T` нумеруются независимо: разбор и выросшая из него задача — разные вещи, и
# делить между ними один счётчик значило бы, что заведение разбора двигает номер задачи.
set -euo pipefail
cd "$(dirname "$0")/.."

kind="${1:-}"
date_arg="${2:-$(date +%Y%m%d)}"

usage() {
  echo "Использование: scripts/next-id.sh {R|T|session} [ГГГГММДД]" >&2
  echo "  R, T     — следующий номер разбора или постановки за дату в docs/tasks/" >&2
  echo "  session  — следующий номер записи сессии за дату в docs/ai_sessions/<дата>/" >&2
  exit 2
}

case "$kind" in
  R|T)
    # Имя вида T-ГГГГММДД-NN-тема-слаг.md. Берётся максимум занятого NN за дату, а не
    # число файлов: дыра в нумерации не должна выдавать уже занятый номер повторно.
    max=$(ls docs/tasks/ 2>/dev/null \
      | sed -nE "s|^${kind}-${date_arg}-0*([0-9]+)-.*\.md$|\1|p" \
      | sort -n | tail -1)
    printf '%s-%s-%02d\n' "$kind" "$date_arg" "$(( ${max:-0} + 1 ))"
    ;;
  session)
    # Пара prompt/response делит один номер, поэтому считается по номеру, а не по файлам.
    dir="docs/ai_sessions/${date_arg:0:4}-${date_arg:4:2}-${date_arg:6:2}"
    max=$(ls "$dir" 2>/dev/null \
      | sed -nE 's|^0*([0-9]+)-.*\.md$|\1|p' \
      | sort -n | tail -1)
    printf '%03d\n' "$(( ${max:-0} + 1 ))"
    ;;
  *)
    usage
    ;;
esac
