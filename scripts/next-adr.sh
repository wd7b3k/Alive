#!/usr/bin/env bash
# Следующий свободный номер ADR. Нумерация разъезжалась дважды за один день
# 27.08.2026: ветка приносила ADR-0004, когда 0004 уже был занят, а пока
# писался ADR о расхождении, владелец параллельно занял 0008. Считать номер
# глазами больше не нужно — считает каталог.
set -euo pipefail
cd "$(dirname "$0")/.."
max=$(ls docs/decisions/ADR-*.md 2>/dev/null | sed -E 's|.*/ADR-0*([0-9]+)-.*|\1|' | sort -n | tail -1)
printf 'ADR-%04d\n' "$(( ${max:-0} + 1 ))"
