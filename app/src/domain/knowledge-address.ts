/**
 * Адрес карточки каталога.
 *
 * Решение владельца 05.09.2026 (ADR-0018): у каждой карточки фактов и мифов свой адрес
 * вида `/knowledge/<код>`, и **этот адрес не меняется**. Смысл решения именно в
 * неизменяемости: адрес, который переехал, теряет всё, что успел набрать в индексе.
 *
 * Поэтому адрес выводится из `code` — первичного ключа `facts_catalog` и
 * `myths_catalog`, — а не из заголовка. Заголовки в этом проекте правятся регулярно:
 * тональность, латинская чистка, русский проход. Код так не правят: на него ссылается
 * `user_myth_state`, и сменить его нельзя, не сломав данные людей.
 *
 * Русский транслитерированный адрес читался бы лучше. Он проиграл сознательно:
 * устойчивость важнее красоты, потому что цена переезда адреса — обнуление индексации,
 * а цена некрасивого адреса — ничего, кроме вкуса.
 *
 * Единственное преобразование — подчёркивание в дефис (`calms_me` → `calms-me`):
 * подчёркивание в адресе поисковики исторически не считают разделителем слов.
 */
export const KNOWLEDGE_BASE = '/knowledge';

/** Код карточки → путь. Обратная операция — `codeFromPath`. */
export function pathForCode(code: string): string {
  return `${KNOWLEDGE_BASE}/${code.replace(/_/g, '-')}`;
}

/**
 * Путь → код карточки, или `null`, если это не адрес карточки.
 *
 * Дефис превращается обратно в подчёркивание. Обратное преобразование однозначно
 * только потому, что в кодах каталога дефисов нет: это проверяет
 * `knowledge-address.test.ts` на настоящей выгрузке.
 */
export function codeFromPath(path: string): string | null {
  const rest = path.startsWith(`${KNOWLEDGE_BASE}/`) ? path.slice(KNOWLEDGE_BASE.length + 1) : '';
  const slug = rest.replace(/\/+$/, '');
  if (!slug || slug.includes('/')) return null;
  if (!/^[a-z0-9-]+$/.test(slug)) return null;
  return slug.replace(/-/g, '_');
}
