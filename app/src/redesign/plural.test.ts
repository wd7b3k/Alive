import { describe, expect, it } from 'vitest';
import { plural } from './utils';

/**
 * На боевом экране висело «19 вещи, которые стоит знать»: форма была вписана в вёрстку
 * руками и совпадала ровно с одним числом. Здесь проверяются именно те числа, на которых
 * ошибается интуиция, — 11–14 против 21–24.
 */
describe('plural', () => {
  const w = (n: number) => `${n} ${plural(n, 'вещь', 'вещи', 'вещей')}`;

  it('берёт форму по последней цифре', () => {
    expect(w(1)).toBe('1 вещь');
    expect(w(2)).toBe('2 вещи');
    expect(w(4)).toBe('4 вещи');
    expect(w(5)).toBe('5 вещей');
    expect(w(19)).toBe('19 вещей'); // тот самый заголовок с боевого экрана
  });

  // Тот самый случай, ради которого правило нельзя писать по последней цифре.
  it('исключает 11–14, где последняя цифра обманывает', () => {
    expect(w(11)).toBe('11 вещей');
    expect(w(12)).toBe('12 вещей');
    expect(w(13)).toBe('13 вещей');
    expect(w(14)).toBe('14 вещей');
    expect(w(21)).toBe('21 вещь');
    expect(w(22)).toBe('22 вещи');
  });

  it('работает за сотней и на нуле', () => {
    expect(w(0)).toBe('0 вещей');
    expect(w(100)).toBe('100 вещей');
    expect(w(101)).toBe('101 вещь');
    expect(w(111)).toBe('111 вещей');
    expect(w(112)).toBe('112 вещей');
    expect(w(121)).toBe('121 вещь');
  });
});
